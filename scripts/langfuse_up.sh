#!/usr/bin/env bash
# Start (or stop) the local self-hosted Langfuse v3 stack.
#
#   scripts/langfuse_up.sh          # generate .env.langfuse if missing, start, wait, print creds
#   scripts/langfuse_up.sh --down   # stop the stack (data volumes are kept)
#
# Idempotent: .env.langfuse is generated once and reused on every rerun.
# Headless init only provisions org/project/keys/user if they don't already exist.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="$ROOT/docker-compose.langfuse.yml"
ENV_FILE="$ROOT/.env.langfuse"
HOST_URL="http://localhost:3000"
TIMEOUT_SECS="${LANGFUSE_UP_TIMEOUT:-300}"

compose() { docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" "$@"; }

if [[ "${1:-}" == "--down" ]]; then
  if [[ ! -f "$ENV_FILE" ]]; then
    # compose needs the variables to parse the file; fall back to project name
    docker compose -p langfuse-local down
  else
    compose down
  fi
  echo "Langfuse stack stopped (volumes kept; add 'docker compose -p langfuse-local down -v' to wipe data)."
  exit 0
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Generating $ENV_FILE with random secrets..."
  hex() { openssl rand -hex "$1"; }
  umask 077
  cat >"$ENV_FILE" <<EOF
# Local Langfuse secrets - generated by scripts/langfuse_up.sh. Git-ignored. Do not commit.
NEXTAUTH_SECRET=$(hex 32)
SALT=$(hex 32)
ENCRYPTION_KEY=$(hex 32)
POSTGRES_PASSWORD=$(hex 16)
CLICKHOUSE_PASSWORD=$(hex 16)
REDIS_AUTH=$(hex 16)
MINIO_ROOT_PASSWORD=$(hex 16)

LANGFUSE_INIT_ORG_ID=local-org
LANGFUSE_INIT_ORG_NAME=Local
LANGFUSE_INIT_PROJECT_ID=supervisor-middleware
LANGFUSE_INIT_PROJECT_NAME=supervisor-middleware
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-local-$(hex 12)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-local-$(hex 16)
LANGFUSE_INIT_USER_EMAIL=admin@localhost.test
LANGFUSE_INIT_USER_NAME=admin
LANGFUSE_INIT_USER_PASSWORD=$(hex 12)
EOF
  chmod 600 "$ENV_FILE"
else
  echo "Using existing $ENV_FILE"
fi

getv() { grep -E "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2-; }

compose up -d

echo -n "Waiting for $HOST_URL/api/public/health (timeout ${TIMEOUT_SECS}s)"
deadline=$((SECONDS + TIMEOUT_SECS))
until curl -sf "$HOST_URL/api/public/health" 2>/dev/null | grep -q '"status":"OK"'; do
  if (( SECONDS >= deadline )); then
    echo
    echo "Timed out waiting for Langfuse. Recent web logs:" >&2
    compose logs --tail 50 langfuse-web >&2 || true
    exit 1
  fi
  echo -n "."
  sleep 3
done
echo " OK"
curl -s "$HOST_URL/api/public/health"; echo

cat <<EOF

Langfuse is up. App environment:
  LANGFUSE_HOST=$HOST_URL
  LANGFUSE_PUBLIC_KEY=$(getv LANGFUSE_INIT_PROJECT_PUBLIC_KEY)
  LANGFUSE_SECRET_KEY=$(getv LANGFUSE_INIT_PROJECT_SECRET_KEY)

UI login ($HOST_URL):
  email:    $(getv LANGFUSE_INIT_USER_EMAIL)
  password: $(getv LANGFUSE_INIT_USER_PASSWORD)
EOF
